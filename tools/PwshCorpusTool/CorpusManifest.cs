        new(slug, input, notes, false, ManifestTransform.None);

    private static ManifestEntry P(string slug, string input, string notes) =>
        new(slug, input, notes, false, ManifestTransform.None, IncludeElements: true);

    private static ManifestEntry S(string slug, string input, string notes) =>
        new(slug, input, notes, false, ManifestTransform.None, IncludeStructure: true);

    private static ManifestEntry V(string slug, string input, string notes) =>
        new(
            slug,
            input,
            notes,
            false,
            ManifestTransform.None,
            IncludeStructure: true,
            IncludeV03Assertions: true);

    private static ManifestEntry A(string slug, string name, string input, string notes) =>
        new(
            slug,
            input,
            notes,
            false,
            ManifestTransform.None,
            IncludeOptionalAssertions: true,
            DisplayName: name);

    private static ManifestEntry Oos(string slug, string input, string notes) =>
        new(slug, input, notes, true, ManifestTransform.None);

    private static ManifestEntry Enc(string slug, string decoded, string notes, bool oos = false) =>
        new(slug, decoded, notes, oos, ManifestTransform.EncodeCommand);

    private static ManifestEntry Big(string slug, string prefix, string notes) =>
        new(slug, prefix, notes, true, ManifestTransform.OversizedInput);

    private static string B64(string s) =>
        Convert.ToBase64String(Encoding.Unicode.GetBytes(s));

    private static string NestIex(string inner, int depth)
    {
        for (var i = 0; i < depth; i++)
        {
            inner = "iex '" + inner.Replace("'", "''") + "'";
        }

        return inner;
    }

