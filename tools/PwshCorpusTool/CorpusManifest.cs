namespace ShellSyntaxTree.Tools.PwshCorpus;

internal enum ManifestTransform
{
    None,
    EncodeCommand,
    OversizedInput,
}

/// <summary>One curated PowerShell corpus input (SPEC.POWERSHELL.md §13).</summary>
internal sealed record ManifestEntry(
    string Slug,
    string RawInput,
    string Notes,
    bool OutOfScope,
    ManifestTransform Transform,
    bool IncludeElements = false,
    bool IncludeStructure = false,
    bool IncludeOptionalAssertions = false,
    bool IncludeV03Assertions = false,
    string? DisplayName = null)
{
    /// <summary>Explicit display name when supplied; otherwise derived from the slug.</summary>
    public string Name =>
        DisplayName ?? (Slug.Length == 0
            ? Slug
            : char.ToUpperInvariant(Slug[0]) + Slug.Substring(1).Replace('_', ' '));

    /// <summary>The actual command string, after applying <see cref="Transform"/>.</summary>
    public string ResolveInput() => Transform switch
    {
        ManifestTransform.EncodeCommand =>
            "pwsh -EncodedCommand " + Convert.ToBase64String(Encoding.Unicode.GetBytes(RawInput)),
        ManifestTransform.OversizedInput =>
            RawInput + new string('a', 70 * 1024),
        _ => RawInput,
    };
}

